"""FastMCP server & A2A discovery card exposing PyTorch Neural Guard, Pinecone, AST Sandbox, and CrewAI/DSPy."""

from typing import Any

from fastmcp import FastMCP

from app.agents.redteam_arena import redteam_arena
from app.core.config import settings
from app.core.logging import get_logger
from app.schemas.security import FirewallInspectRequest
from app.security.ast_sandbox import ast_security_sandbox
from app.security.pinecone_threat_store import CANONICAL_OWASP_SIGNATURES
from app.security.zero_trust_gateway import zero_trust_gateway

logger = get_logger(__name__)

mcp_server = FastMCP(
    name=f"{settings.APP_NAME} - Zero-Trust MCP Server",
    instructions=(
        "Exposes multi-layer AI security tools: PyTorch Multi-Head Self-Attention threat classification, "
        "Pinecone OWASP vector matching, Python AST formal code verification, and CrewAI/DSPy Red-Teaming."
    ),
)


@mcp_server.tool()
async def inspect_prompt_and_code_zero_trust(
    prompt: str,
    generated_code: str | None = None,
    target_mcp_tool: str = "execute_agent_task",
) -> dict[str, Any]:
    """
    Inspect a prompt and optional generated Python code across PyTorch Self-Attention,
    Shannon Entropy, Pinecone vector threat signatures, PII redaction, and AST sandbox.

    Args:
        prompt: Raw user prompt, RAG document chunk, or instruction to inspect.
        generated_code: Optional Python code snippet to verify via formal AST visitor.
        target_mcp_tool: Name of the downstream MCP tool being protected.
    """
    logger.info(
        "MCP Tool [inspect_prompt_and_code_zero_trust] invoked for tool=%s", target_mcp_tool)
    req = FirewallInspectRequest(
        prompt=prompt,
        generated_code=generated_code,
        target_mcp_tool=target_mcp_tool,
    )
    decision = zero_trust_gateway.inspect(req)
    return decision.model_dump(mode="json")


@mcp_server.tool()
async def verify_python_ast_sandbox(code: str) -> dict[str, Any]:
    """
    Statically verify Python code using Abstract Syntax Tree (AST) traversal to block
    OS command execution, forbidden imports, dunder sandbox escapes, and infinite loops.

    Args:
        code: Python source code snippet generated by an LLM.
    """
    logger.info("MCP Tool [verify_python_ast_sandbox] invoked")
    result = ast_security_sandbox.verify_code(code)
    return result.model_dump(mode="json")


@mcp_server.tool()
async def execute_crewai_dspy_redteam_audit(
    initial_system_prompt: str = (
        "You are an enterprise AI assistant with access to internal MCP tools and Python execution."
    ),
) -> dict[str, Any]:
    """
    Run an autonomous CrewAI Red-Team adversarial campaign across OWASP LLM Top-10 vectors
    and compile a self-hardened system prompt using DSPy BootstrapFewShot invariants.

    Args:
        initial_system_prompt: Base system prompt to audit and harden.
    """
    logger.info("MCP Tool [execute_crewai_dspy_redteam_audit] invoked")
    campaign = redteam_arena.run_campaign(
        initial_system_prompt=initial_system_prompt)
    return campaign.model_dump(mode="json")


@mcp_server.resource("security://owasp/pinecone-threat-signatures")
async def get_owasp_threat_signatures_resource() -> dict[str, Any]:
    """Expose canonical OWASP LLM Top-10 threat signatures indexed in the Pinecone vector store."""
    return {
        "index_name": settings.PINECONE_INDEX_NAME,
        "similarity_threshold": settings.PINECONE_SIMILARITY_THRESHOLD,
        "signatures": [
            {
                "signature_id": sig.signature_id,
                "attack_name": sig.attack_name,
                "owasp_category": sig.owasp_category.value,
            }
            for sig in CANONICAL_OWASP_SIGNATURES
        ],
    }


def get_a2a_security_agent_card() -> dict[str, Any]:
    """Return standardized Agent-to-Agent (A2A) discovery metadata for `/.well-known/agent.json`."""
    return {
        "agent_id": "a2a-zero-trust-neural-firewall-guardian",
        "name": settings.APP_NAME,
        "version": settings.APP_VERSION,
        "protocol": "A2A-1.0 + FastMCP",
        "description": (
            "Autonomous Zero-Trust AI Security Guardian providing PyTorch Self-Attention threat scoring, "
            "Pinecone vector signature matching, Python AST static sandbox verification, and DSPy prompt hardening."
        ),
        "capabilities": [
            "pytorch_self_attention_threat_classification",
            "pinecone_owasp_vector_threat_matching",
            "python_ast_formal_code_verification",
            "crewai_adversarial_red_teaming",
            "dspy_declarative_prompt_hardening",
        ],
        "endpoints": {
            "inspect": f"{settings.API_V1_PREFIX}/firewall/inspect",
            "ast_verify": f"{settings.API_V1_PREFIX}/sandbox/verify-ast",
            "redteam_campaign": f"{settings.API_V1_PREFIX}/redteam/campaign",
        },
    }


if __name__ == "__main__":
    mcp_server.run()
