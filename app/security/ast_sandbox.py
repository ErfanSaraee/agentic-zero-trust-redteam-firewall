"""Formal Python Abstract Syntax Tree (AST) static security verifier for LLM-generated code."""

import ast

from app.core.config import settings
from app.schemas.security import ASTVerificationResult

FORBIDDEN_MODULES: set[str] = {
    "os",
    "subprocess",
    "sys",
    "shutil",
    "socket",
    "pty",
    "ctypes",
    "pickle",
    "marshal",
    "builtins",
    "importlib",
}

FORBIDDEN_BUILTINS: set[str] = {
    "eval",
    "exec",
    "compile",
    "__import__",
    "open",
    "getattr",
    "setattr",
    "delattr",
    "globals",
    "locals",
    "breakpoint",
}

FORBIDDEN_DUNDER_ATTRS: set[str] = {
    "__subclasses__",
    "__globals__",
    "__builtins__",
    "__mro__",
    "__bases__",
    "__class__",
    "__code__",
    "__closure__",
}


class _SecurityASTVisitor(ast.NodeVisitor):
    """AST NodeVisitor inspecting imports, calls, dunder attributes, and unbounded loops."""

    def __init__(self) -> None:
        self.violations: list[str] = []
        self.visited_nodes: list[str] = []
        self.complexity: int = 1

    def generic_visit(self, node: ast.AST) -> None:
        node_name = type(node).__name__
        if len(self.visited_nodes) < 40:
            self.visited_nodes.append(node_name)
        super().generic_visit(node)

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            root_mod = alias.name.split(".")[0]
            if root_mod in FORBIDDEN_MODULES:
                self.violations.append(
                    f"Line {node.lineno}: Forbidden module import '{alias.name}' (Sandbox RCE risk)."
                )
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.module:
            root_mod = node.module.split(".")[0]
            if root_mod in FORBIDDEN_MODULES:
                self.violations.append(
                    f"Line {node.lineno}: Forbidden from-import '{node.module}' (Sandbox RCE risk)."
                )
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        if isinstance(node.func, ast.Name) and node.func.id in FORBIDDEN_BUILTINS:
            self.violations.append(
                f"Line {node.lineno}: Prohibited builtin call '{node.func.id}()' detected."
            )
        elif isinstance(node.func, ast.Attribute):
            attr_name = node.func.attr
            if attr_name in {"system", "popen", "rmtree", "remove", "unlink", "spawn"}:
                self.violations.append(
                    f"Line {node.lineno}: Destructive/OS method call '.{attr_name}()' prohibited."
                )
        self.generic_visit(node)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        if node.attr in FORBIDDEN_DUNDER_ATTRS:
            self.violations.append(
                f"Line {node.lineno}: Sandbox escape dunder attribute '{node.attr}' prohibited."
            )
        self.generic_visit(node)

    def visit_If(self, node: ast.If) -> None:
        self.complexity += 1
        self.generic_visit(node)

    def visit_For(self, node: ast.For) -> None:
        self.complexity += 1
        self.generic_visit(node)

    def visit_While(self, node: ast.While) -> None:
        self.complexity += 1
        if isinstance(node.test, ast.Constant) and node.test.value is True:
            has_exit = any(
                isinstance(child, (ast.Break, ast.Return, ast.Raise))
                for child in ast.walk(node)
            )
            if not has_exit:
                self.violations.append(
                    f"Line {node.lineno}: Unbounded infinite loop 'while True:' without break/return."
                )
        self.generic_visit(node)


class PythonASTSecuritySandbox:
    """Stateless formal verifier for Python code generated by LLMs or autonomous agents."""

    @staticmethod
    def verify_code(code: str | None) -> ASTVerificationResult:
        """Parse and statically verify Python code against Zero-Trust AST safety invariants."""
        if not code or not code.strip():
            return ASTVerificationResult(
                code_provided=False,
                is_safe=True,
                cyclomatic_complexity=0,
                violations=[],
                visited_ast_nodes=[],
            )

        try:
            tree = ast.parse(code)
        except SyntaxError as exc:
            return ASTVerificationResult(
                code_provided=True,
                is_safe=False,
                cyclomatic_complexity=0,
                violations=[f"SyntaxError at line {exc.lineno}: {exc.msg}"],
                visited_ast_nodes=["SyntaxError"],
            )

        visitor = _SecurityASTVisitor()
        visitor.visit(tree)

        if visitor.complexity > settings.MAX_AST_COMPLEXITY_SCORE:
            visitor.violations.append(
                f"Cyclomatic complexity ({visitor.complexity}) exceeds max threshold ({settings.MAX_AST_COMPLEXITY_SCORE})."
            )

        return ASTVerificationResult(
            code_provided=True,
            is_safe=len(visitor.violations) == 0,
            cyclomatic_complexity=visitor.complexity,
            violations=visitor.violations,
            visited_ast_nodes=visitor.visited_nodes,
        )


ast_security_sandbox = PythonASTSecuritySandbox()
